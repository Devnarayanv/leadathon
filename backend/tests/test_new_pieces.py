def test_igst_rate_is_used_as_is():
    facts = [
        Fact(key="subtotal", label="Subtotal", value="1000.00"),
        Fact(key="igst", label="IGST", value="180.00"),
        Fact(key="igst_rate", label="IGST rate", value="18%"),
        Fact(key="total_amount", label="Total", value="1180.00"),
    ]
    report = verification.verify("invoice", facts, [])
    checks = {c.key: c for c in report.checks}
    assert checks["tax"].status == "verified"
    assert checks["tax"].calculated_value == "Rs. 180.00"
    assert checks["grand_total"].status == "verified"


# ---- invoice vs purchase order ---------------------------------------------

def _as_comparable(result, doc_type):
    return ComparableDocument(
        analysis_id=result.analysis_id,
        filename=result.filename,
        doc_type=doc_type,
        facts=result.facts,
        line_items=result.line_items,
    )


def test_invoice_vs_purchase_order_finds_total_and_item_difference():
    invoice = _analyse_demo("sample_invoice_mismatch")
    order = _analyse_demo("sample_purchase_order")
    out = comparison.compare(
        _as_comparable(invoice, "invoice"), _as_comparable(order, "purchase_order")
    )
    assert out.comparable is True
    assert out.kind == "invoice_vs_purchase_order"
    rows = {r.label: r for r in out.field_rows}
    assert rows["Supplier"].result == "match"
    assert rows["Buyer"].result == "match"
    assert rows["Total"].result == "mismatch"
    cable = [r for r in out.item_rows if "cable" in r.label.lower()]
    assert cable and cable[0].result == "mismatch"


def test_compare_refuses_two_invoices_with_same_number_as_duplicate():
    invoice = _analyse_demo("sample_invoice_mismatch")
    a = _as_comparable(invoice, "invoice")
    b = _as_comparable(invoice, "invoice")
    out = comparison.compare(a, b)
    assert out.comparable is False
    assert out.kind == "duplicate_invoice"


