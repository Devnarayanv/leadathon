def _analyse_demo(demo_id: str):
    data = demo_catalog.file_bytes(demo_id)
    assert data is not None, "demo file missing: %s (run demo/make_demo_docs.py)" % demo_id
    filename = demo_catalog.filename_for(demo_id)
    return pipeline.analyse(filename, "application/pdf", data, "en", use_ai=False)


# ---- money -----------------------------------------------------------------

def test_money_parses_indian_grouping_and_lakh_words():
    assert money.parse("Rs. 3,050.00") == Decimal("3050.00")
    assert money.parse("Rs. 12,50,000.00") == Decimal("1250000.00")
    assert money.parse("2.5 lakh") == Decimal("250000")
    assert money.parse("45000/-") == Decimal("45000")


def test_money_returns_none_not_zero_when_nothing_is_stated():
    assert money.parse(None) is None
    assert money.parse("") is None
    assert money.parse("no figures here") is None


def test_money_fmt_uses_indian_grouping_and_dash_for_missing():
    assert money.fmt(Decimal("1250000")) == "Rs. 12,50,000.00"
    assert money.fmt(Decimal("3599")) == "Rs. 3,599.00"
    assert money.fmt(None) == "—"


def test_money_tolerance_is_one_rupee():
    assert money.within_tolerance(Decimal("100.00"), Decimal("100.99"))
    assert not money.within_tolerance(Decimal("100.00"), Decimal("101.01"))


def test_line_item_quantity_keeps_plain_digits():
    # Regression: str(Decimal("10").normalize()) gave "1E+1", which money.parse read as 1.
    items = line_items.extract([(1, "Steel bolts 10 120.00 1200.00")])
    assert items, "expected one row"
    assert items[0].quantity == "10"


# ---- invoice mismatch -------------------------------------------------------

def test_invoice_mismatch_flags_exactly_the_wrong_row():
    result = _analyse_demo("sample_invoice_mismatch")
    assert result.classification.doc_type == "invoice"
    assert result.verification.status == "mismatch"
    mismatches = [c for c in result.verification.checks if c.status == "mismatch"]
    assert [c.key for c in mismatches] == ["line_3"]
    assert mismatches[0].document_value == "Rs. 350.00"
    assert mismatches[0].calculated_value == "Rs. 300.00"
    # One finding for the wrong row (carrying the corrected total), plus the
    # Net-30 payment deadline. The corrected total is not a second error.
    wrong = [f for f in result.findings if f.category == "verification_required"]
    assert len(wrong) == 1
    assert "Cable clips" in wrong[0].title
    assert "Rs. 3,540.00" in wrong[0].suggested_action
    assert wrong[0].ref in {a.finding_ref for a in result.actions}
    assert any(f.category == "deadline" for f in result.findings)


def test_invoice_mismatch_row_arithmetic_is_not_a_false_positive():
    result = _analyse_demo("sample_invoice_mismatch")
